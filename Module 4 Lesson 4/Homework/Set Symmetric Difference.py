Set1_A = {'blue', 'green'}
Set2_A = {'blue', 'yellow'}

symmetric_diff_A = Set1_A.symmetric_difference(Set2_A)
print("Symmetric Difference for Set A:", symmetric_diff_A)

Set1_B = {1, 2, 3, 4, 5}
